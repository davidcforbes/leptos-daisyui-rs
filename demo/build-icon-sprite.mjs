// Generates demo/icons.svg, the showcase's inline icon sprite (ldui-kcs7).
//
// `Icon` renders `<use href="#<symbol>">` against a sprite the HOST page
// inlines, and maps Lucide-style names onto the 4Ease symbol ids that
// 4iiz-Office's sprite defines (src/components/icon/component.rs). The
// showcase inlined no sprite at all, so every `Icon` here drew an empty box.
// Office's sprite is that app's own artwork in a private repository, so the
// showcase draws the same symbol ids with Lucide's ISC-licensed glyphs
// instead.
//
// Run from demo/:   node build-icon-sprite.mjs
// Re-run whenever the map in src/components/icon/component.rs gains a symbol;
// tests/demo_icon_sprite.rs fails until you do.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const MAP_SOURCE = "../src/components/icon/component.rs";
const LUCIDE = "node_modules/lucide-static";
const OUT = "icons.svg";
const STROKE =
  'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';

// Symbol ids neither the map's keys nor the id itself name a Lucide glyph
// for. `blank` is the map's DELIBERATE empty glyph ("circle" => "blank", and
// the fallback for an unmapped name), so it must stay empty.
const OVERRIDES = new Map([
  ["refresh", "refresh-cw"],
  ["whatsapp", "message-circle"], // Lucide ships no brand logos.
  ["blank", null],
]);

const src = readFileSync(MAP_SOURCE, "utf8");
const start = src.indexOf("fn lucide_to_sprite_inner");
if (start < 0) throw new Error(`no lucide_to_sprite_inner in ${MAP_SOURCE}`);
const body = src.slice(start, src.indexOf("\n}\n", start));

// symbol id -> the names that map to it, in source order.
const symbols = new Map();
const arm = /((?:"[^"]+"\s*\|\s*)*"[^"]+")\s*=>\s*"([^"]+)"/g;
for (const [, keys, symbol] of body.matchAll(arm)) {
  const names = [...keys.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  symbols.set(symbol, [...(symbols.get(symbol) ?? []), ...names]);
}
if (symbols.size < 10) throw new Error(`parsed only ${symbols.size} symbols; did the map change shape?`);

const version = JSON.parse(readFileSync(`${LUCIDE}/package.json`, "utf8")).version;
const available = new Set(
  readdirSync(`${LUCIDE}/icons`).filter((f) => f.endsWith(".svg")).map((f) => f.slice(0, -4)),
);

const inner = (glyph) => {
  const svg = readFileSync(`${LUCIDE}/icons/${glyph}.svg`, "utf8");
  const open = svg.indexOf(">", svg.indexOf("<svg"));
  return svg
    .slice(open + 1, svg.lastIndexOf("</svg>"))
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .join("");
};

const out = [];
const missing = [];
for (const [symbol, names] of symbols) {
  let glyph;
  if (OVERRIDES.has(symbol)) glyph = OVERRIDES.get(symbol);
  else glyph = [...names, symbol].find((n) => available.has(n));
  if (glyph === undefined) {
    missing.push(`${symbol} (${names.join(", ")})`);
    continue;
  }
  const paths = glyph === null ? "" : inner(glyph);
  const from = glyph === null ? "deliberately empty" : `lucide:${glyph}`;
  // The stroke attributes go on each <symbol>: a `<use>` clone inherits from
  // the `<use>` element, never from the original <defs>, so attributes on
  // <defs> would leave every glyph a filled black blob.
  out.push(
    `    <!-- ${from} --><symbol id="${symbol}" viewBox="0 0 24 24" ${STROKE}>${paths}</symbol>`,
  );
}
if (missing.length) {
  throw new Error(`no Lucide glyph for: ${missing.join("; ")}. Add an OVERRIDES entry.`);
}

const sprite = `<!--
  GENERATED by demo/build-icon-sprite.mjs (ldui-kcs7) -- do not edit by hand.
  Glyphs from lucide-static ${version}, ISC License, Copyright (c) Lucide
  Contributors (https://lucide.dev/license). Symbol ids are the ones
  leptos-daisyui-rs's Icon maps to (src/components/icon/component.rs).
-->
<svg xmlns="http://www.w3.org/2000/svg" style="display: none" aria-hidden="true" focusable="false">
  <defs>
${out.join("\n")}
  </defs>
</svg>
`;
writeFileSync(OUT, sprite);
console.log(`wrote ${OUT}: ${out.length} symbols from lucide-static ${version}`);
