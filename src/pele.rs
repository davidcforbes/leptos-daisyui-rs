pub fn pele_worker_url_for(asset_base: Option<&str>) -> String {
    asset_url(asset_base, PELE_WORKER_FILE)
}

/// A fresh accessibility-ID prefix (`ldui-pele-<n>-`) for one diagram.
///
/// pele namespaces each SVG's title/description IDs with `idPrefix`; two
/// diagrams on one page sharing a prefix would make `aria-labelledby`
/// resolve to the wrong diagram.
pub fn next_id_prefix() -> String {
    let n = NEXT_DIAGRAM.with(|c| {
        let n = c.get().wrapping_add(1);
        c.set(n);
        n
    });
    format!("ldui-pele-{n}-")
}

/// Escape text for an HTML text or attribute context.
///
/// pele's error messages quote diagram source, so they never reach
/// `inner_html` unescaped.
pub fn escape_html(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c => out.push(c),
        }
    }
    out
}

