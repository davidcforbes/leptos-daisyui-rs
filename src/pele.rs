/// Why a diagram could not be drawn: pele's own `PeleError` fields, or a
/// failure around it (`load`, `timeout`, `render`, `sanitize`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PeleRenderError {
    /// Description of the problem. Contains diagram source: display as text.
    pub message: String,
    /// pele's error code (`syntax`, `semantic`, `unsupported-diagram`,
    /// `limit`), or `load` (the worker could not start), `timeout` (the
    /// diagram overran [`PELE_RENDER_TIMEOUT_MS`]), `render` (anything else
    /// pele threw) or `sanitize` (the SVG could not be parsed).
    pub code: String,
    /// 1-based line of the problem, `0` when there is no position.
    pub line: u32,
    /// 1-based column of the problem, `0` when there is no position.
    pub column: u32,
    /// The offending source line plus a caret line; empty without a position.
    pub snippet: String,
}

impl PeleRenderError {
    /// An error with no source position.
    pub fn new(code: &str, message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
            code: code.to_string(),
            line: 0,
            column: 0,
            snippet: String::new(),
        }
    }

    /// The worker at `url` could not start or load pele (missing file, CSP).
    pub fn load_failed(url: &str) -> Self {
        Self::new(
            "load",
            format!("could not start the Mermaid renderer (pele {PELE_VERSION}) from {url}"),
        )
    }

    /// The diagram overran its time limit of `limit_ms` and was stopped.
    pub fn timed_out(limit_ms: u32) -> Self {
        Self::new(
            "timeout",
            if limit_ms.is_multiple_of(1000) {
                format!(
                    "the diagram took longer than {} s to draw and was stopped",
                    limit_ms / 1000
                )
            } else {
                format!("the diagram took longer than {limit_ms} ms to draw and was stopped")
            },
        )
    }

    /// Read an error object (a `PeleError`, the worker's error record, or
    /// anything else that was thrown).
    pub fn from_js(thrown: &JsValue) -> Self {
        let field = |name: &str| Reflect::get(thrown, &JsValue::from_str(name)).ok();
        let text = |name: &str| field(name).and_then(|v| v.as_string()).unwrap_or_default();
        let number = |name: &str| {
            field(name)
                .and_then(|v| v.as_f64())
                .filter(|n| n.is_finite() && *n >= 0.0)
                .map(|n| n as u32)
                .unwrap_or(0)
        };
        let message = field("message")
            .and_then(|v| v.as_string())
            .or_else(|| thrown.as_string())
            .filter(|m| !m.trim().is_empty())
            .unwrap_or_else(|| "unknown error".to_string());
        let mut code = text("code");
        if code.is_empty() {
            code = "render".to_string();
        }
        Self {
            message,
            code,
            line: number("line"),
            column: number("column"),
            snippet: text("snippet"),
        }
    }

    /// One-line, human-readable description.
    pub fn summary(&self) -> String {
        format!("Diagram error: {}", self.message)
    }

    /// The library's `mermaid-error` markup, every byte of pele's text
    /// escaped. The snippet (source line plus caret) follows the summary in
    /// the same `pre`, so the caret stays aligned.
    pub fn to_html(&self) -> String {
        let mut text = self.summary();
        if !self.snippet.is_empty() {
            text.push('\n');
            text.push_str(&self.snippet);
        }
        format!(
            "<pre class=\"mermaid-error whitespace-pre-wrap\" data-pele-error=\"{}\">{}</pre>",
            escape_html(&self.code),
            escape_html(&text)
        )
    }
}

impl fmt::Display for PeleRenderError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.summary())
    }
}

impl std::error::Error for PeleRenderError {}

